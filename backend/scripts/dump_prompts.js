/**
 * Writes docs/PROMPTS_FULL.md: the exact system prompt and user message each LLM call sends, for one sample
 * animal in English (and the report also in Urdu). Uses a fake client, so no API key or network is needed.
 *
 * Usage: cd backend && node scripts/dump_prompts.js
 */
const fs = require("fs");
const path = require("path");
const llm = require("../services/llm");

process.env.LLM_API_KEY = process.env.LLM_API_KEY || "not-used";

// Records each request and answers with output that passes the schema
const calls = [];
const replies = {
  breed: { breed: "Sahiwal", confidence: 0.7, inKnownClasses: true, reasoning: "Reddish coat, loose skin, large dewlap." },
  report: {
    summary: "s",
    reasons: ["a", "b"],
    risks: ["r"],
    purposeFit: "p",
    tips: ["Watch one full milking.", "Ask for the vaccination record.", "Check the udder and teats."]
  },
  chat: { answer: "a", suggestions: ["x", "y", "z"] },
  compare: { reason: "r" }
};
let next = null;
llm._setClient({
  messages: {
    parse: async (params) => {
      calls.push({ kind: next, params });
      return { stop_reason: "end_turn", parsed_output: replies[next] };
    }
  }
});

const rules = {
  verdict: "caution",
  score: 64,
  purposeFitLevel: "strong",
  reasons: ["No signs of Foot-and-Mouth or Lumpy Skin Disease in the photos.", "Sahiwal is a strong fit for milk."],
  risks: ["The seller's price is 30% above your budget."],
  flags: ["over_budget", "age_uncertain"]
};
const ctx = (language) => ({
  purpose: "milk",
  language,
  budget: 200000,
  sellerPrice: 260000,
  experience: "first_time",
  species: { species: "cow", confidence: 0.95 },
  breed: { label: "Sahiwal", confidence: 0.82, uncertain: false, source: "model+llm" },
  age: { age_years: 4, interval_90: [3, 6], permanent_incisors_estimate: 6, uncertain: false, quality: { ok: true } },
  health: { condition: "healthy", confidence: 0.93 },
  rules
});
const evaluation = {
  purpose: "milk",
  language: "en",
  budget: 200000,
  sellerPrice: 260000,
  verdict: "caution",
  score: 64,
  results: {
    species: { species: "cow" },
    breed: { final: { label: "Sahiwal", uncertain: false } },
    age: { age_years: 4, uncertain: false },
    health: { condition: "healthy" }
  },
  report: { summary: "Sahiwal cow for milk: healthy, but the price is high.", reasons: rules.reasons, risks: rules.risks }
};

const show = (content) => {
  if (typeof content === "string") return content;
  return content
    .map((b) => (b.type === "text" ? b.text : `[${b.type}: one side photo, JPEG, base64]`))
    .join("\n\n");
};

(async () => {
  next = "breed";
  await llm.verifyBreed({
    image: { buffer: Buffer.from("photo"), mimetype: "image/jpeg" },
    species: "cow",
    modelTop3: [{ breed: "Sahiwal", confidence: 0.61 }, { breed: "Red Sindhi", confidence: 0.2 }, { breed: "Gir", confidence: 0.1 }]
  });
  next = "report";
  await llm.generateReport(ctx("en"));
  await llm.generateReport(ctx("ur"));
  next = "chat";
  await llm.answerQuestion({
    evaluation,
    history: [{ role: "user", content: "Is she pregnant?" }, { role: "assistant", content: "Photos can't show that; ask a vet to check." }],
    question: "How much milk will she give?"
  });
  next = "compare";
  await llm.explainComparison({
    purpose: "milk",
    language: "en",
    winner: { letter: "A", score: 78, verdict: "recommended", breed: "Sahiwal", ageYears: 4, health: "healthy", fit: "strong" },
    other: { letter: "B", score: 52, verdict: "caution", breed: "Jersey", ageYears: 9, health: "healthy", fit: "strong" }
  });

  const titles = { breed: "Breed check from a side photo", report: "Buying report", chat: "Question about one animal", compare: "Comparing two animals" };
  const out = [
    "# LLM prompts: full text",
    "",
    "Generated by `backend/scripts/dump_prompts.js` from `backend/services/llm.js`. Re-run it after changing a prompt. " +
      "The sample animal and answers are made up; only the prompt wording is real. Design notes and version history: [PROMPTS.md](PROMPTS.md).",
    ""
  ];
  const seen = {};
  for (const { kind, params } of calls) {
    const version = llm.PROMPT_VERSIONS[kind];
    seen[kind] = (seen[kind] || 0) + 1;
    const lang = kind === "report" ? (seen[kind] === 1 ? " (English)" : " (Urdu)") : "";
    out.push(`## ${titles[kind]}${lang}: \`${version}\``, "");
    out.push(`Model \`${params.model}\`, max_tokens ${params.max_tokens}, effort \`${params.output_config.effort}\`, structured JSON output.`, "");
    out.push("**System prompt**", "", "```text", params.system, "```", "");
    out.push("**User message**", "", "```text", show(params.messages[0].content), "```", "");
  }
  const file = path.join(__dirname, "..", "..", "docs", "PROMPTS_FULL.md");
  fs.writeFileSync(file, out.join("\n"));
  console.log(`Wrote ${file} (${calls.length} prompts)`);
})().catch((error) => {
  console.error(error);
  process.exit(1);
});
